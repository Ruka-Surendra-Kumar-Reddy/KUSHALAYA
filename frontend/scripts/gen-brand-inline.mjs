// Regenerates lib/brand-inline.ts from the PNGs in public/brand.
//
// Why the logo is inlined at all: even with preload + fetchPriority=high +
// a year-long cache, a first visit still fetched the mark as a separate
// request that shared bandwidth with ~300KB of JS. nginx 1.20 ignores the
// browser's HTTP/2 stream priorities, so on a slow link the logo finished
// when the scripts did — ~1.5s after the page had painted. A data URI is
// part of the HTML, so the logo paints with the first frame, every time.
//
// Run after replacing a file in public/brand:   node scripts/gen-brand-inline.mjs
// lib/brand-inline.test.ts fails if this output no longer matches the files.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Only the marks that sit above the fold on every page. The 512px PWA icon is
// too large to inline and is only rendered by the assessor shell.
const VARIANTS = {
  header: "kushalaya-header.png",
  lockup: "kushalaya-lockup.png",
};

function pngSize(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error("not a PNG");
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

let out = `// GENERATED by scripts/gen-brand-inline.mjs — do not edit by hand.
// Regenerate whenever a file in public/brand changes.
/* eslint-disable */

export type BrandInlineVariant = ${Object.keys(VARIANTS)
  .map((k) => JSON.stringify(k))
  .join(" | ")};

export const BRAND_INLINE_SIZE: Record<BrandInlineVariant, { width: number; height: number }> = {
`;
const uris = [];
for (const [variant, file] of Object.entries(VARIANTS)) {
  const buf = readFileSync(join(root, "public", "brand", file));
  const { width, height } = pngSize(buf);
  out += `  ${variant}: { width: ${width}, height: ${height} },\n`;
  uris.push([variant, `data:image/png;base64,${buf.toString("base64")}`, buf.length]);
}
out += `};\n\n/** Data URIs of the marks — bytes: ${uris
  .map(([v, , n]) => `${v}=${n}`)
  .join(", ")} */\nexport const BRAND_INLINE: Record<BrandInlineVariant, string> = {\n`;
for (const [variant, uri] of uris) {
  out += `  ${variant}:\n    ${JSON.stringify(uri)},\n`;
}
out += "};\n";

const target = join(root, "lib", "brand-inline.ts");
writeFileSync(target, out);
console.log(`wrote ${target}`);
for (const [v, uri, n] of uris) console.log(`  ${v}: ${n} bytes -> ${uri.length} chars`);
