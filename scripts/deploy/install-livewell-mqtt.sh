#!/usr/bin/env bash
# Install Mosquitto for LiveWell IoT on the same host as the API.
# Idempotent: safe to re-run; preserves passwd/credentials unless --force-passwords.
#
# Default: native package (dnf/yum) — no Docker required.
# Optional: --docker if you prefer the eclipse-mosquitto container.
#
#   sudo -iu safehomeops
#   cd /opt/safehomeops/app
#   sudo bash scripts/deploy/install-livewell-mqtt.sh
#
set -euo pipefail

[[ ${EUID:-0} -eq 0 ]] || {
  echo "ERROR: Run as root: sudo bash $0" >&2
  echo "  Tip: as safehomeops → cd /opt/safehomeops/app && sudo bash scripts/deploy/install-livewell-mqtt.sh" >&2
  exit 1
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_ROOT="${APP_ROOT:-/opt/safehomeops/app}"
APP_USER="${APP_USER:-safehomeops}"
APP_DOMAIN="${APP_DOMAIN:-ops.kushalaya.com}"
MQTT_SRC="${APP_ROOT}/deploy/mqtt"
MQTT_RUNTIME="${MQTT_RUNTIME:-/var/lib/safehomeops/mqtt}"
SKIP_FIREWALL=0
FORCE_PASSWORDS=0
USE_DOCKER=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --docker) USE_DOCKER=1; shift ;;
    --skip-firewall) SKIP_FIREWALL=1; shift ;;
    --force-passwords) FORCE_PASSWORDS=1; shift ;;
    --app-root) APP_ROOT="$2"; MQTT_SRC="${APP_ROOT}/deploy/mqtt"; shift 2 ;;
    --runtime-dir) MQTT_RUNTIME="$2"; shift 2 ;;
    --domain) APP_DOMAIN="$2"; shift 2 ;;
    -h|--help)
      sed -n '1,18p' "$0"
      exit 0
      ;;
    *)
      echo "Unknown arg: $1" >&2
      exit 1
      ;;
  esac
done

log() { echo "==> $*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

as_app() {
  runuser -u "$APP_USER" -- "$@"
}

[[ -d "$APP_ROOT" ]] || die "Missing APP_ROOT=$APP_ROOT"
id "$APP_USER" >/dev/null 2>&1 || die "User $APP_USER not found"
as_app test -d "$MQTT_SRC" || die "Missing $MQTT_SRC — git pull as $APP_USER first"
as_app test -f "$MQTT_SRC/acl" || die "Missing acl in $MQTT_SRC"

LE_LIVE="/etc/letsencrypt/live/${APP_DOMAIN}"
[[ -f "${LE_LIVE}/fullchain.pem" && -f "${LE_LIVE}/privkey.pem" ]] \
  || die "TLS certs not found at ${LE_LIVE}/ — run certbot for ${APP_DOMAIN} first"

mkdir -p "${MQTT_RUNTIME}/certs" "${MQTT_RUNTIME}/data"
as_app cat "${MQTT_SRC}/acl" >"${MQTT_RUNTIME}/acl"

cp -f "${LE_LIVE}/fullchain.pem" "${MQTT_RUNTIME}/certs/fullchain.pem"
cp -f "${LE_LIVE}/privkey.pem" "${MQTT_RUNTIME}/certs/privkey.pem"
log "Runtime MQTT dir: ${MQTT_RUNTIME}"

CRED_FILE="${MQTT_RUNTIME}/.credentials"
PASSWD_FILE="${MQTT_RUNTIME}/passwd"
CRED_APP="${MQTT_RUNTIME}/.credentials.app"
CRED_LINK="${MQTT_SRC}/.credentials"

gen_pw() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 24 | tr -d '/+=' | head -c 24
  else
    head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 24
  fi
}

sync_credentials_app() {
  # Ensure safehomeops-readable copy exists whenever root credentials do.
  if [[ -f "$CRED_FILE" ]]; then
    install -o "$APP_USER" -g "$APP_USER" -m 600 "$CRED_FILE" "$CRED_APP"
    cp -f "$CRED_APP" "$CRED_LINK" 2>/dev/null \
      && chown "${APP_USER}:${APP_USER}" "$CRED_LINK" && chmod 600 "$CRED_LINK" || true
  fi
}

write_credentials() {
  local ingest_pw="$1" hub_pw="$2"
  umask 077
  cat >"$CRED_FILE" <<EOF
# Generated by install-livewell-mqtt.sh — do not commit
# $(date -u +%Y-%m-%dT%H:%M:%SZ)
MQTT_INGESTOR_USER=livewell_ingestor
MQTT_INGESTOR_PASSWORD=${ingest_pw}
MQTT_HUB_USER=mg7_home1
MQTT_HUB_PASSWORD=${hub_pw}
MQTT_PUBLIC_HOST=${APP_DOMAIN}
MQTT_PUBLIC_PORT=8883
MQTT_LOCAL_HOST=127.0.0.1
MQTT_LOCAL_PORT=1883
MQTT_RUNTIME=${MQTT_RUNTIME}
MQTT_MODE=$([ "$USE_DOCKER" -eq 1 ] && echo docker || echo native)
EOF
  chmod 600 "$CRED_FILE"
  sync_credentials_app
}

create_users() {
  local ingest_pw hub_pw
  if [[ -f "$PASSWD_FILE" && "$FORCE_PASSWORDS" -eq 0 ]]; then
    log "Reusing existing ${PASSWD_FILE} (idempotent; --force-passwords to rotate)"
    if [[ -f "$CRED_FILE" ]]; then
      # Refresh host/runtime metadata but keep passwords
      ingest_pw="$(grep -E '^MQTT_INGESTOR_PASSWORD=' "$CRED_FILE" | cut -d= -f2- || true)"
      hub_pw="$(grep -E '^MQTT_HUB_PASSWORD=' "$CRED_FILE" | cut -d= -f2- || true)"
      if [[ -n "$ingest_pw" && -n "$hub_pw" ]]; then
        write_credentials "$ingest_pw" "$hub_pw"
      else
        sync_credentials_app
      fi
    elif [[ -f "$CRED_APP" ]]; then
      cp -f "$CRED_APP" "$CRED_FILE"
      chmod 600 "$CRED_FILE"
      sync_credentials_app
    else
      die "passwd exists but no credentials file — re-run with --force-passwords (will rotate MQTT passwords)"
    fi
    return
  fi

  ingest_pw="$(gen_pw)"
  hub_pw="$(gen_pw)"
  rm -f "$PASSWD_FILE"

  if ! command -v mosquitto_passwd >/dev/null 2>&1; then
    die "mosquitto_passwd not found — install mosquitto package first"
  fi
  mosquitto_passwd -b -c "$PASSWD_FILE" livewell_ingestor "$ingest_pw"
  mosquitto_passwd -b "$PASSWD_FILE" mg7_home1 "$hub_pw"
  chmod 600 "$PASSWD_FILE"
  write_credentials "$ingest_pw" "$hub_pw"
  log "Wrote MQTT users → ${PASSWD_FILE}"
  log "Wrote secrets → ${CRED_FILE} and ${CRED_APP}"
}

open_firewall_8883() {
  if [[ "$SKIP_FIREWALL" -eq 1 ]]; then
    log "Skipping firewall (--skip-firewall)"
    return
  fi
  if command -v firewall-cmd >/dev/null 2>&1 && systemctl is-active --quiet firewalld 2>/dev/null; then
    firewall-cmd --permanent --add-port=8883/tcp >/dev/null || true
    firewall-cmd --reload >/dev/null || true
    log "firewalld: 8883/tcp allowed (idempotent)"
  elif command -v ufw >/dev/null 2>&1; then
    ufw status 2>/dev/null | grep -q '8883/tcp' \
      || ufw allow 8883/tcp comment 'MQTT TLS LiveWell IoT' || true
    log "ufw: 8883/tcp allowed (idempotent)"
  else
    log "No firewalld/ufw — open TCP 8883 in your cloud security list manually"
  fi
}

enable_ol9_epel() {
  dnf install -y oracle-epel-release-el9 2>/dev/null || true
  if command -v dnf >/dev/null 2>&1; then
    dnf config-manager --set-enabled ol9_developer_EPEL 2>/dev/null \
      || dnf config-manager --enable ol9_developer_EPEL 2>/dev/null || true
    dnf config-manager --set-enabled ol9_codeready_builder 2>/dev/null \
      || dnf config-manager --enable ol9_codeready_builder 2>/dev/null || true
    dnf config-manager --set-enabled ol9_distro_builder 2>/dev/null || true
    dnf install -y https://dl.fedoraproject.org/pub/epel/epel-release-latest-9.noarch.rpm 2>/dev/null || true
    dnf config-manager --set-enabled epel 2>/dev/null || true
  fi
}

install_mosquitto_rpm_direct() {
  local arch ver base tmp
  arch="$(uname -m)"
  ver="2.0.22-1.el9"
  base="https://dl.fedoraproject.org/pub/epel/9/Everything/${arch}/Packages/m"
  tmp="$(mktemp -d)"
  log "Trying direct EPEL RPM download (${arch}, mosquitto-${ver})…"
  if ! curl -fsSL -o "${tmp}/mosquitto.rpm" "${base}/mosquitto-${ver}.${arch}.rpm"; then
    rm -rf "$tmp"
    return 1
  fi
  if dnf install -y "${tmp}/mosquitto.rpm"; then
    rm -rf "$tmp"
    return 0
  fi
  if rpm -Uvh "${tmp}/mosquitto.rpm"; then
    rm -rf "$tmp"
    return 0
  fi
  rm -rf "$tmp"
  return 1
}

install_mosquitto_from_source() {
  local ver="2.0.22" src="/usr/local/src/mosquitto-${ver}"
  log "Building Mosquitto ${ver} from source (fallback)…"
  dnf install -y gcc make cmake openssl-devel c-ares-devel libuuid-devel wget tar 2>/dev/null \
    || yum install -y gcc make cmake openssl-devel c-ares-devel libuuid-devel wget tar 2>/dev/null \
    || true
  mkdir -p /usr/local/src
  cd /usr/local/src
  if [[ ! -f "mosquitto-${ver}.tar.gz" ]]; then
    curl -fsSL -o "mosquitto-${ver}.tar.gz" \
      "https://mosquitto.org/files/source/mosquitto-${ver}.tar.gz"
  fi
  rm -rf "$src"
  tar -xzf "mosquitto-${ver}.tar.gz"
  cd "$src"
  if [[ -f CMakeLists.txt ]]; then
    cmake -DCMAKE_INSTALL_PREFIX=/usr -DWITH_SYSTEMD=ON -DDOCUMENTATION=OFF .
    cmake --build . -j"$(nproc 2>/dev/null || echo 2)"
    cmake --install .
  else
    make -j"$(nproc 2>/dev/null || echo 2)"
    make install
  fi
  command -v mosquitto >/dev/null 2>&1 || die "Source build finished but mosquitto not on PATH"
  if [[ ! -f /etc/systemd/system/mosquitto.service && ! -f /usr/lib/systemd/system/mosquitto.service ]]; then
    cat >/etc/systemd/system/mosquitto.service <<'EOF'
[Unit]
Description=Mosquitto MQTT Broker (LiveWell)
After=network.target

[Service]
Type=simple
ExecStart=/usr/sbin/mosquitto -c /etc/mosquitto/mosquitto.conf
ExecReload=/bin/kill -HUP $MAINPID
Restart=on-failure
User=mosquitto
Group=mosquitto

[Install]
WantedBy=multi-user.target
EOF
    if [[ -x /usr/local/sbin/mosquitto ]]; then
      sed -i 's|/usr/sbin/mosquitto|/usr/local/sbin/mosquitto|' /etc/systemd/system/mosquitto.service
    elif [[ -x /usr/bin/mosquitto ]]; then
      sed -i 's|/usr/sbin/mosquitto|/usr/bin/mosquitto|' /etc/systemd/system/mosquitto.service
    fi
    getent passwd mosquitto >/dev/null || useradd -r -s /sbin/nologin -d /var/lib/mosquitto mosquitto || true
    mkdir -p /etc/mosquitto /var/lib/mosquitto /var/log/mosquitto
    [[ -f /etc/mosquitto/mosquitto.conf ]] || echo 'include_dir /etc/mosquitto/conf.d' >/etc/mosquitto/mosquitto.conf
    systemctl daemon-reload
  fi
  command -v mosquitto_passwd >/dev/null 2>&1 || die "mosquitto_passwd missing after source build"
}

ensure_mosquitto_installed() {
  if command -v mosquitto >/dev/null 2>&1; then
    log "mosquitto already installed: $(command -v mosquitto)"
    return 0
  fi

  if command -v dnf >/dev/null 2>&1; then
    enable_ol9_epel
    log "dnf makecache (EPEL)…"
    dnf makecache 2>/dev/null || true
    if dnf install -y mosquitto mosquitto-clients; then
      return 0
    fi
    log "dnf package not found — trying direct EPEL RPM…"
    if install_mosquitto_rpm_direct; then
      dnf install -y mosquitto-clients 2>/dev/null || true
      return 0
    fi
  elif command -v yum >/dev/null 2>&1; then
    yum install -y epel-release 2>/dev/null || true
    yum install -y mosquitto mosquitto-clients && return 0
  elif command -v apt-get >/dev/null 2>&1; then
    apt-get update -y
    apt-get install -y mosquitto mosquitto-clients && return 0
  fi

  log "Package install failed — building from source"
  install_mosquitto_from_source
}

apply_native_permissions() {
  local mq_user="mosquitto"
  id "$mq_user" >/dev/null 2>&1 || mq_user="root"
  mkdir -p "${MQTT_RUNTIME}/data" "${MQTT_RUNTIME}/certs" /var/log/mosquitto /run/mosquitto /etc/mosquitto/conf.d
  # Do not chown -R the whole runtime (would fight .credentials.app); set precisely
  chown "${mq_user}:${mq_user}" "${MQTT_RUNTIME}" "${MQTT_RUNTIME}/data" "${MQTT_RUNTIME}/certs" \
    "${MQTT_RUNTIME}/acl" "$PASSWD_FILE" /var/log/mosquitto 2>/dev/null || true
  chown "${mq_user}:${mq_user}" "${MQTT_RUNTIME}/certs/fullchain.pem" "${MQTT_RUNTIME}/certs/privkey.pem"
  chmod 755 "$MQTT_RUNTIME" "${MQTT_RUNTIME}/data" "${MQTT_RUNTIME}/certs"
  chmod 640 "$PASSWD_FILE" 2>/dev/null || true
  chmod 644 "${MQTT_RUNTIME}/certs/fullchain.pem" "${MQTT_RUNTIME}/acl"
  chmod 600 "${MQTT_RUNTIME}/certs/privkey.pem"
  sync_credentials_app
}

apply_native_config() {
  local conf_src conf_dst
  as_app test -f "${MQTT_SRC}/mosquitto-native.conf" \
    || die "Missing ${MQTT_SRC}/mosquitto-native.conf — git pull"
  conf_src="${MQTT_SRC}/mosquitto-native.conf"
  conf_dst="/etc/mosquitto/conf.d/livewell.conf"
  mkdir -p /etc/mosquitto/conf.d
  as_app cat "$conf_src" >"$conf_dst"
  chmod 644 "$conf_dst"
  log "Wrote ${conf_dst}"

  if [[ -f /etc/mosquitto/conf.d/default.conf ]]; then
    mv -f /etc/mosquitto/conf.d/default.conf /etc/mosquitto/conf.d/default.conf.disabled
    log "Disabled conf.d/default.conf"
  fi

  # Stock OL/EPEL mosquitto.conf is huge and often ends with a broken empty
  # `include_dir` (Error: Empty include_dir value … line 905). Always replace
  # with a stub; keep one timestamped backup if the current file isn't already ours.
  mkdir -p /etc/mosquitto
  if [[ -f /etc/mosquitto/mosquitto.conf ]]; then
    if ! grep -q 'Managed by install-livewell-mqtt.sh' /etc/mosquitto/mosquitto.conf 2>/dev/null; then
      local bak="/etc/mosquitto/mosquitto.conf.pre-livewell.$(date +%Y%m%d%H%M%S)"
      cp -a /etc/mosquitto/mosquitto.conf "$bak"
      log "Backed up stock mosquitto.conf → ${bak}"
    fi
    if [[ ! -f /etc/mosquitto/mosquitto.conf.pre-livewell ]]; then
      cp -a /etc/mosquitto/mosquitto.conf /etc/mosquitto/mosquitto.conf.pre-livewell 2>/dev/null || true
    fi
  fi
  cat >/etc/mosquitto/mosquitto.conf <<'EOF'
# Managed by install-livewell-mqtt.sh — LiveWell IoT (idempotent)
# Do not append package sample lines; LiveWell config is only under conf.d/
include_dir /etc/mosquitto/conf.d
EOF
  chmod 644 /etc/mosquitto/mosquitto.conf
  log "Wrote minimal /etc/mosquitto/mosquitto.conf (include_dir /etc/mosquitto/conf.d)"
}

validate_and_restart_native() {
  # Stop first so foreground test does not hit "Address already in use" on re-runs
  if systemctl list-unit-files mosquitto.service >/dev/null 2>&1; then
    systemctl stop mosquitto 2>/dev/null || true
  fi
  # Also kill stray mosquitto if any
  pkill -x mosquitto 2>/dev/null || true
  sleep 0.5

  local mosq_bin
  mosq_bin="$(command -v mosquitto || true)"
  [[ -x "$mosq_bin" ]] || mosq_bin=/usr/sbin/mosquitto

  log "Validating Mosquitto config (2s foreground test)…"
  set +e
  timeout 2 "$mosq_bin" -c /etc/mosquitto/mosquitto.conf -v \
    >/tmp/mosquitto-livewell-test.log 2>&1
  local rc=$?
  set -e
  # 124 = timeout (broker stayed up) → OK
  if [[ "$rc" -ne 0 && "$rc" -ne 124 ]]; then
    echo "---- mosquitto -v output ----" >&2
    cat /tmp/mosquitto-livewell-test.log >&2 || true
    die "Mosquitto config failed. Fix certs/passwd/acl then re-run (idempotent)."
  fi
  log "Foreground test OK (rc=${rc})"

  systemctl enable mosquitto >/dev/null 2>&1 || true
  systemctl restart mosquitto
  sleep 1
  if ! systemctl is-active --quiet mosquitto; then
    echo "---- journalctl -u mosquitto -n 50 ----" >&2
    journalctl -u mosquitto -n 50 --no-pager >&2 || true
    die "mosquitto.service not active — sudo $mosq_bin -c /etc/mosquitto/mosquitto.conf -v"
  fi
  systemctl --no-pager --full status mosquitto || true
  log "Native Mosquitto is active"
}

install_native() {
  log "Installing/refreshing native Mosquitto (idempotent)"
  ensure_mosquitto_installed
  command -v mosquitto >/dev/null 2>&1 || die "mosquitto still not installed"
  command -v mosquitto_passwd >/dev/null 2>&1 || die "mosquitto_passwd missing"

  create_users
  apply_native_permissions
  apply_native_config
  open_firewall_8883
  validate_and_restart_native
}

install_docker() {
  log "Installing/refreshing Mosquitto via Docker (idempotent, --docker)"
  command -v docker >/dev/null 2>&1 || die "docker not installed — omit --docker for native package"
  docker compose version >/dev/null 2>&1 || die "docker compose plugin required"

  as_app test -f "$MQTT_SRC/mosquitto.conf" || die "Missing docker mosquitto.conf"
  as_app test -f "$MQTT_SRC/docker-compose.yml" || die "Missing docker-compose.yml"
  as_app cat "${MQTT_SRC}/mosquitto.conf" >"${MQTT_RUNTIME}/mosquitto.conf"
  as_app cat "${MQTT_SRC}/docker-compose.yml" >"${MQTT_RUNTIME}/docker-compose.yml"

  if command -v mosquitto_passwd >/dev/null 2>&1; then
    create_users
  else
    if [[ -f "$PASSWD_FILE" && "$FORCE_PASSWORDS" -eq 0 ]]; then
      log "Reusing existing ${PASSWD_FILE}"
      sync_credentials_app
    else
      local ingest_pw hub_pw
      ingest_pw="$(gen_pw)"
      hub_pw="$(gen_pw)"
      rm -f "$PASSWD_FILE"
      docker run --rm -v "${MQTT_RUNTIME}:/mosquitto/config" eclipse-mosquitto:2 \
        mosquitto_passwd -b -c /mosquitto/config/passwd livewell_ingestor "$ingest_pw"
      docker run --rm -v "${MQTT_RUNTIME}:/mosquitto/config" eclipse-mosquitto:2 \
        mosquitto_passwd -b /mosquitto/config/passwd mg7_home1 "$hub_pw"
      write_credentials "$ingest_pw" "$hub_pw"
    fi
  fi

  chown -R 1883:1883 "${MQTT_RUNTIME}/certs" "$PASSWD_FILE" \
    "${MQTT_RUNTIME}/mosquitto.conf" "${MQTT_RUNTIME}/acl" 2>/dev/null || true
  sync_credentials_app
  open_firewall_8883
  cd "$MQTT_RUNTIME"
  docker compose up -d --remove-orphans
  docker compose ps
  log "Docker Mosquitto is up"
}

if [[ "$USE_DOCKER" -eq 1 ]]; then
  install_docker
else
  install_native
fi

log "Mosquitto install complete (re-run safe)."
echo ""
echo "  Mode:     $([ "$USE_DOCKER" -eq 1 ] && echo docker || echo native)"
echo "  Public:   ${APP_DOMAIN}:8883 (TLS) — MG7 user mg7_home1"
echo "  Local:    127.0.0.1:1883 — ingestor user livewell_ingestor"
echo "  Runtime:  ${MQTT_RUNTIME}"
echo "  Secrets:  ${CRED_APP}  (as ${APP_USER})"
echo ""
echo "Next: sudo bash ${SCRIPT_DIR}/install-livewell-iot-ingestor.sh"
