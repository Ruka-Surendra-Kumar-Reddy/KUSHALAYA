#!/usr/bin/env bash
# Install LiveWell IoT MQTT ingestor (venv deps + env + systemd).
# Idempotent: safe to re-run; preserves IOT_DEVICE_MAP unless --elder-map is passed.
#
#   cd /opt/safehomeops/app   # as safehomeops
#   sudo bash scripts/deploy/install-livewell-iot-ingestor.sh \
#     --elder-map '{"aa:bb:cc:dd:ee:ff":42}'
#
set -euo pipefail

[[ ${EUID:-0} -eq 0 ]] || {
  echo "ERROR: Run as root: sudo bash $0" >&2
  echo "  Tip: as safehomeops → cd /opt/safehomeops/app && sudo bash $0 ..." >&2
  exit 1
}

APP_ROOT="${APP_ROOT:-/opt/safehomeops/app}"
APP_USER="${APP_USER:-safehomeops}"
BACKEND="${APP_ROOT}/backend"
MQTT_RUNTIME="${MQTT_RUNTIME:-/var/lib/safehomeops/mqtt}"
MQTT_SRC="${APP_ROOT}/deploy/mqtt"
ENV_FILE="${BACKEND}/iot_ingestor.env"
API_ENV="${BACKEND}/.env"
UNIT_SRC="${APP_ROOT}/deploy/systemd/safehomeops-iot-ingestor.service"
SKIP_RESTART_API=0
ELDER_MAP=""
ELDER_MAP_SET=0
SKIP_MQTT_USERS=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --elder-map) ELDER_MAP="$2"; ELDER_MAP_SET=1; shift 2 ;;
    --skip-restart-api) SKIP_RESTART_API=1; shift ;;
    --skip-mqtt-users) SKIP_MQTT_USERS=1; shift ;;
    --runtime-dir) MQTT_RUNTIME="$2"; shift 2 ;;
    --app-root) APP_ROOT="$2"; BACKEND="${APP_ROOT}/backend"; MQTT_SRC="${APP_ROOT}/deploy/mqtt"
      ENV_FILE="${BACKEND}/iot_ingestor.env"; API_ENV="${BACKEND}/.env"
      UNIT_SRC="${APP_ROOT}/deploy/systemd/safehomeops-iot-ingestor.service"; shift 2 ;;
    -h|--help)
      sed -n '1,12p' "$0"
      exit 0
      ;;
    *)
      echo "Unknown arg: $1" >&2
      exit 1
      ;;
  esac
done

log() { echo "==> $*" >&2; }
die() { echo "ERROR: $*" >&2; exit 1; }

as_app() {
  runuser -u "$APP_USER" -- "$@"
}

id "$APP_USER" >/dev/null 2>&1 || die "User $APP_USER not found"
as_app test -d "$BACKEND" || die "Missing $BACKEND (login as $APP_USER and git pull)"
as_app test -f "$UNIT_SRC" || die "Missing $UNIT_SRC"

gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    head -c 32 /dev/urandom | xxd -p -c 64
  fi
}

ensure_api_key() {
  local key=""
  if as_app test -f "$API_ENV" && as_app grep -qE '^IOT_INGEST_API_KEY=.' "$API_ENV"; then
    key="$(as_app grep -E '^IOT_INGEST_API_KEY=' "$API_ENV" | tail -1 | cut -d= -f2- | tr -d '\r')"
    log "Using existing IOT_INGEST_API_KEY (idempotent)"
  else
    key="$(gen_secret)"
    if as_app test -f "$API_ENV"; then
      as_app bash -c "printf '\\n# LiveWell IoT ingest\\nIOT_INGEST_API_KEY=%s\\n' '$key' >>'$API_ENV'"
    else
      as_app bash -c "printf 'IOT_INGEST_API_KEY=%s\\n' '$key' >'$API_ENV'"
      as_app chmod 600 "$API_ENV"
    fi
    log "Appended IOT_INGEST_API_KEY to ${API_ENV}"
    if [[ "$SKIP_RESTART_API" -eq 0 ]]; then
      systemctl restart safehomeops-api || die "Failed to restart safehomeops-api"
      log "Restarted safehomeops-api"
    fi
  fi
  printf '%s' "$key"
}

load_mqtt_password() {
  local cred=""
  for cand in \
    "${MQTT_RUNTIME}/.credentials.app" \
    "${MQTT_RUNTIME}/.credentials" \
    "${MQTT_SRC}/.credentials"; do
    if [[ -f "$cand" ]]; then
      cred="$cand"
      break
    fi
    if as_app test -f "$cand" 2>/dev/null; then
      cred="$cand"
      break
    fi
  done
  [[ -n "$cred" ]] || {
    if [[ "$SKIP_MQTT_USERS" -eq 1 ]]; then
      die "No MQTT credentials found. Run install-livewell-mqtt.sh first."
    fi
    die "Missing MQTT credentials under ${MQTT_RUNTIME}. Run install-livewell-mqtt.sh first."
  }

  # shellcheck disable=SC1090
  set -a
  # shellcheck source=/dev/null
  source <(grep -E '^[A-Z0-9_]+=' "$cred" || as_app grep -E '^[A-Z0-9_]+=' "$cred" || true)
  set +a

  if [[ -n "${MQTT_INGESTOR_PASSWORD:-}" ]]; then
    printf '%s' "$MQTT_INGESTOR_PASSWORD"
    return
  fi
  die "MQTT_INGESTOR_PASSWORD missing in $cred"
}

resolve_device_map() {
  # Prefer explicit --elder-map; else keep existing env; else {}
  if [[ "$ELDER_MAP_SET" -eq 1 ]]; then
    log "Using --elder-map from command line"
    printf '%s' "$ELDER_MAP"
    return
  fi
  if as_app test -f "$ENV_FILE" && as_app grep -qE '^IOT_DEVICE_MAP=' "$ENV_FILE"; then
    log "Preserving existing IOT_DEVICE_MAP from ${ENV_FILE}"
    as_app grep -E '^IOT_DEVICE_MAP=' "$ENV_FILE" | tail -1 | cut -d= -f2-
    return
  fi
  printf '%s' '{}'
}

API_KEY="$(ensure_api_key)"
MQTT_PW="$(load_mqtt_password)"
DEVICE_MAP="$(resolve_device_map)"

VENV_PY="${BACKEND}/.venv/bin/python"
VENV_PIP="${BACKEND}/.venv/bin/pip"
if ! as_app test -x "$VENV_PY"; then
  log "Creating venv at ${BACKEND}/.venv"
  as_app python3 -m venv "${BACKEND}/.venv"
fi
log "Ensuring iot_ingestor Python deps (as ${APP_USER})"
as_app "$VENV_PIP" install -q -r "${BACKEND}/iot_ingestor/requirements.txt"

as_app bash -c "cat >'$ENV_FILE' <<EOF
# Generated by install-livewell-iot-ingestor.sh — $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Idempotent re-runs preserve IOT_DEVICE_MAP unless --elder-map is passed.
MQTT_HOST=127.0.0.1
MQTT_PORT=1883
MQTT_USERNAME=livewell_ingestor
MQTT_PASSWORD=${MQTT_PW}
MQTT_TLS=0
MQTT_TOPIC=livewell/homes/+/hubs/+/ble,mg7/+/status,/mg7/+/status
LIVEWELL_API_BASE=http://127.0.0.1:8010
IOT_INGEST_API_KEY=${API_KEY}
IOT_DEVICE_MAP=${DEVICE_MAP}
IOT_DEDUPE_SECONDS=65
LOG_LEVEL=INFO
EOF
chmod 600 '$ENV_FILE'
"
log "Wrote ${ENV_FILE} (owner ${APP_USER})"

as_app cat "$UNIT_SRC" >/etc/systemd/system/safehomeops-iot-ingestor.service
chmod 644 /etc/systemd/system/safehomeops-iot-ingestor.service

systemctl daemon-reload
systemctl enable safehomeops-iot-ingestor >/dev/null 2>&1 || true
systemctl restart safehomeops-iot-ingestor
sleep 1
if ! systemctl is-active --quiet safehomeops-iot-ingestor; then
  journalctl -u safehomeops-iot-ingestor -n 40 --no-pager >&2 || true
  die "safehomeops-iot-ingestor failed to start"
fi
systemctl status safehomeops-iot-ingestor --no-pager || true

log "Ingestor install complete (re-run safe)."
echo ""
echo "  Status:  systemctl status safehomeops-iot-ingestor"
echo "  Logs:    journalctl -u safehomeops-iot-ingestor -f"
echo "  Map:     sudo -u ${APP_USER} nano ${ENV_FILE}"
echo "           then: sudo systemctl restart safehomeops-iot-ingestor"
echo ""
if [[ "$DEVICE_MAP" == "{}" ]]; then
  echo "  WARNING: IOT_DEVICE_MAP is empty {}. Pass --elder-map '{\"mac\":elder_id}'"
fi
